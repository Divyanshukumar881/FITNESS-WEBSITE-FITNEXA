create extension if not exists pgcrypto;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '', email text not null default '', age integer,
  gender text, height_cm numeric, weight_kg numeric,
  fitness_goal text, fitness_level text, updated_at timestamptz not null default now()
);
create table if not exists public.memberships (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  plan text not null default 'FREE' check (plan in ('FREE','PRO','PREMIUM')),
  starts_at timestamptz not null default now(), ends_at timestamptz,
  status text not null default 'active', payment_status text not null default 'not_required',
  created_at timestamptz not null default now()
);
create table if not exists public.workout_history (
  id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id) on delete cascade,
  program_id text, workout_name text not null, duration_minutes integer not null default 0,
  completed_at timestamptz not null default now()
);
create table if not exists public.weight_entries (
  id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id) on delete cascade,
  weight_kg numeric not null check(weight_kg > 0 and weight_kg < 1000), goal_weight_kg numeric,
  recorded_at timestamptz not null default now()
);
create table if not exists public.sleep_entries (
  id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id) on delete cascade,
  sleep_time text not null, wake_time text not null, duration_minutes integer not null,
  recorded_at timestamptz not null default now()
);
create table if not exists public.products (
  id text primary key, name text not null, price integer not null check(price >= 0),
  stock integer not null default 100 check(stock >= 0), active boolean not null default true
);
create table if not exists public.cart_items (
  id bigint generated by default as identity primary key, user_id uuid not null references auth.users(id) on delete cascade,
  item_type text not null check(item_type in ('product','membership')), item_id text not null,
  name text not null, quantity integer not null check(quantity between 1 and 99),
  unit_price integer not null check(unit_price >= 0), billing_period text not null default '',
  created_at timestamptz not null default now(), unique(user_id,item_type,item_id,billing_period)
);
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(), user_id uuid not null references auth.users(id) on delete cascade,
  customer_name text, total integer not null check(total >= 0), currency text not null default 'INR',
  payment_status text not null default 'pending', order_status text not null default 'pending',
  created_at timestamptz not null default now()
);
create table if not exists public.order_items (
  id bigint generated by default as identity primary key, order_id uuid not null references public.orders(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade, item_type text not null,
  item_id text not null, name text not null, quantity integer not null, unit_price integer not null,
  billing_period text not null default ''
);
create table if not exists public.trainer_requests (
  id bigint generated by default as identity primary key, user_id uuid not null references auth.users(id) on delete cascade,
  trainer_id text not null, message text not null default '', status text not null default 'pending',
  created_at timestamptz not null default now()
);

