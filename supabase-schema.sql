create or replace function public.fitnexa_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles(user_id,full_name,email)
  values(new.id,coalesce(new.raw_user_meta_data->>'full_name',''),coalesce(new.email,''))
  on conflict(user_id) do nothing;
  insert into public.memberships(user_id,plan,status,payment_status)
  values(new.id,'FREE','active','not_required');
  return new;
end; $$;
drop trigger if exists fitnexa_auth_user_created on auth.users;
create trigger fitnexa_auth_user_created after insert on auth.users
for each row execute function public.fitnexa_new_user();

create or replace function public.add_fitnexa_cart_item(p_item_type text,p_item_id text,p_quantity integer default 1,p_billing_period text default 'Monthly')
returns setof public.cart_items language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); pname text; price integer; period text := '';
begin
  if uid is null then raise exception 'Sign in required'; end if;
  if p_item_type = 'product' then
    select name,products.price into pname,price from public.products where id=p_item_id and active and stock >= greatest(1,least(coalesce(p_quantity,1),99));
    if pname is null then raise exception 'Product unavailable'; end if;
  elsif p_item_type = 'membership' then
    if upper(p_item_id) not in ('FREE','PRO','PREMIUM') then raise exception 'Unknown plan'; end if;
    pname := upper(p_item_id) || ' Membership';
    price := case upper(p_item_id) when 'PRO' then 499 when 'PREMIUM' then 999 else 0 end;
    period := case when p_billing_period = 'Yearly' then 'Yearly' else 'Monthly' end;
    if period = 'Yearly' then price := round(price * 0.8)::integer; end if;
  else raise exception 'Invalid cart item type'; end if;
  insert into public.cart_items(user_id,item_type,item_id,name,quantity,unit_price,billing_period)
  values(uid,p_item_type,p_item_id,pname,case when p_item_type='membership' then 1 else greatest(1,least(coalesce(p_quantity,1),99)) end,price,period)
  on conflict(user_id,item_type,item_id,billing_period) do update set
    quantity=case when p_item_type='membership' then 1 else least(public.cart_items.quantity + excluded.quantity,99) end,
    unit_price=excluded.unit_price;
  return query select * from public.cart_items c where c.user_id=uid order by c.id;
end; $$;

revoke all on function public.add_fitnexa_cart_item(text,text,integer,text) from public, anon;
grant execute on function public.add_fitnexa_cart_item(text,text,integer,text) to authenticated;

create or replace function public.create_fitnexa_order(p_customer_name text default '')
returns jsonb language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid(); oid uuid; grand_total integer;
begin
  if uid is null then raise exception 'Sign in required'; end if;
  if not exists(select 1 from public.cart_items where user_id=uid) then raise exception 'Your cart is empty'; end if;
  select sum(unit_price*quantity*case when item_type='membership' and billing_period='Yearly' then 12 else 1 end)
  into grand_total from public.cart_items where user_id=uid;
  insert into public.orders(user_id,customer_name,total) values(uid,left(p_customer_name,120),grand_total) returning id into oid;
  insert into public.order_items(order_id,user_id,item_type,item_id,name,quantity,unit_price,billing_period)
  select oid,uid,item_type,item_id,name,quantity,unit_price,billing_period from public.cart_items where user_id=uid;
  delete from public.cart_items where user_id=uid;
  return jsonb_build_object('id',oid,'total',grand_total,'payment_status','pending','order_status','pending');
end; $$;
revoke all on function public.create_fitnexa_order(text) from public, anon;
grant execute on function public.create_fitnexa_order(text) to authenticated;

